CREATE TABLE families(id TEXT PRIMARY KEY,name TEXT NOT NULL,companions TEXT NOT NULL,diaper TEXT NOT NULL,created TEXT NOT NULL);
CREATE TABLE gifts(id TEXT PRIMARY KEY,name TEXT NOT NULL,image TEXT NOT NULL,url TEXT NOT NULL,capacity INTEGER NOT NULL CHECK(capacity>0));
CREATE TABLE reservations(family_id TEXT PRIMARY KEY REFERENCES families(id),gift_id TEXT NOT NULL REFERENCES gifts(id));
CREATE INDEX reservations_gift ON reservations(gift_id);
CREATE TABLE settings(id INTEGER PRIMARY KEY CHECK(id=1),date TEXT NOT NULL DEFAULT '',time TEXT NOT NULL DEFAULT '',location TEXT NOT NULL DEFAULT '');
